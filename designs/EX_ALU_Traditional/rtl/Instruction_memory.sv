module Data_memory(
    input  logic        clk,
    input  logic        we,
    input  logic [31:0] A,
    input  logic [31:0] wd,
    input  logic [2:0]  funct3,
    output logic [31:0] RD
);

    //========================================================
    // 64 KB Data Memory
    // 16384 words x 32 bits = 64 KB
    //========================================================
    logic [31:0] RAM [16383:0];

    integer i;

    //========================================================
    // INITIALIZE DATA MEMORY = 0
    //========================================================
    initial begin

        for (i = 0; i < 16384; i = i + 1)
            RAM[i] = 32'd0;

        $display("==============================================");
        $display("[DMEM] Data memory initialized to ZERO");
        $display("==============================================");

    end


    //========================================================
    // READ
    //========================================================
    always_comb begin

        case (funct3)

            //================================================
            // LB
            //================================================
            3'b000: begin

                case (A[1:0])

                    2'b00:
                        RD = {{24{RAM[A[15:2]][7]}},
                              RAM[A[15:2]][7:0]};

                    2'b01:
                        RD = {{24{RAM[A[15:2]][15]}},
                              RAM[A[15:2]][15:8]};

                    2'b10:
                        RD = {{24{RAM[A[15:2]][23]}},
                              RAM[A[15:2]][23:16]};

                    2'b11:
                        RD = {{24{RAM[A[15:2]][31]}},
                              RAM[A[15:2]][31:24]};

                endcase

            end


            //================================================
            // LH
            //================================================
            3'b001: begin

                if (A[1] == 1'b0)

                    RD = {{16{RAM[A[15:2]][15]}},
                          RAM[A[15:2]][15:0]};

                else

                    RD = {{16{RAM[A[15:2]][31]}},
                          RAM[A[15:2]][31:16]};

            end


            //================================================
            // LW
            //================================================
            3'b010: begin

                RD = RAM[A[15:2]];

            end


            //================================================
            // LBU
            //================================================
            3'b100: begin

                case (A[1:0])

                    2'b00:
                        RD = {24'd0,
                              RAM[A[15:2]][7:0]};

                    2'b01:
                        RD = {24'd0,
                              RAM[A[15:2]][15:8]};

                    2'b10:
                        RD = {24'd0,
                              RAM[A[15:2]][23:16]};

                    2'b11:
                        RD = {24'd0,
                              RAM[A[15:2]][31:24]};

                endcase

            end


            //================================================
            // LHU
            //================================================
            3'b101: begin

                if (A[1] == 1'b0)

                    RD = {16'd0,
                          RAM[A[15:2]][15:0]};

                else

                    RD = {16'd0,
                          RAM[A[15:2]][31:16]};

            end


            //================================================
            // DEFAULT
            //================================================
            default: begin

                RD = RAM[A[15:2]];

            end

        endcase

    end


    //========================================================
    // WRITE
    //========================================================
    always_ff @(posedge clk) begin

        if (we) begin

            case (funct3)

                //================================================
                // SB
                //================================================
                3'b000: begin

                    case (A[1:0])

                        2'b00:
                            RAM[A[15:2]][7:0]
                                <= wd[7:0];

                        2'b01:
                            RAM[A[15:2]][15:8]
                                <= wd[7:0];

                        2'b10:
                            RAM[A[15:2]][23:16]
                                <= wd[7:0];

                        2'b11:
                            RAM[A[15:2]][31:24]
                                <= wd[7:0];

                    endcase

                end


                //================================================
                // SH
                //================================================
                3'b001: begin

                    if (A[1] == 1'b0)

                        RAM[A[15:2]][15:0]
                            <= wd[15:0];

                    else

                        RAM[A[15:2]][31:16]
                            <= wd[15:0];

                end


                //================================================
                // SW
                //================================================
                3'b010: begin

                    RAM[A[15:2]] <= wd;

                end


                //================================================
                // DEFAULT
                //================================================
                default: begin

                    RAM[A[15:2]] <= wd;

                end

            endcase

        end

    end

endmodule